"""Run everything, write docs/TEST_REPORT.md, docs/VALIDATION.md and SHA256SUMS.txt from the REAL run.
Usage: python scripts/check.py        (exit code 0 only if every check passed)"""
import datetime, hashlib, platform, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def run(cmd):
    r = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True)
    return r.returncode, (r.stdout + r.stderr).strip()


def main():
    steps = [("unit + durability + experiment tests", [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"]),
             ("demo", [sys.executable, "src/demo.py"]),
             ("compile", [sys.executable, "-m", "py_compile", "src/singulyar_runtime.py", "src/sqlite_ledger.py",
                          "src/schema_validate.py", "src/demo.py", "experiments/ablation.py"])]
    results = [(name, *run(cmd)) for name, cmd in steps]
    node = run(["node", "-e", "global.window={};const fs=require('fs');eval(fs.readFileSync('prototype/replay_data.js','utf8')"
                ".replace('const REPLAY','global.REPLAY'));if(!REPLAY.length)process.exit(1);console.log(REPLAY.length+' scenarios parse')"])
    results.append(("replay data parses (node)", *node))
    ok = all(rc == 0 for _, rc, _ in results)
    stamp = f"{datetime.date.today().isoformat()} · Python {platform.python_version()} · {platform.system()}"
    body = [f"# Test report (generated by scripts/check.py)\n\nRun: {stamp}\n"]
    for name, rc, out in results:
        body.append(f"## {name}\nExit code: {rc}\n\n```text\n{out}\n```\n")
    body.append("Interpretation: passing tests cover the listed scenarios only. They do not establish production readiness, "
                "security, real-network behaviour or novelty. See docs/LIMITATIONS.md.\n")
    (ROOT / "docs" / "TEST_REPORT.md").write_text("\n".join(body), encoding="utf-8")
    (ROOT / "docs" / "VALIDATION.md").write_text(
        "# Validation summary\n\n" + "\n".join(f"- {n}: exit {rc}" for n, rc, _ in results) +
        ("\n\nAll recorded checks passed.\n" if ok else "\n\nAT LEAST ONE CHECK FAILED - do not accept.\n"), encoding="utf-8")
    lines = []
    for p in sorted(ROOT.rglob("*")):
        if p.is_file() and p.name != "SHA256SUMS.txt" and "__pycache__" not in p.parts:
            lines.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(ROOT).as_posix()}")
    (ROOT / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("ALL CHECKS PASSED" if ok else "FAILED")
    for n, rc, _ in results:
        print(f"  {n}: {rc}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
