"""runtime/src/adr_amender.py — Decree-Driven ADR Amendment Mechanism (per ADR-0026).

The AdrAmender class processes decrees with category='amendment' and:
1. Parses the decree text to identify the operation + target ADR(s)
2. Validates the operation against ADR-0016 lifecycle rules
3. Applies the amendment — either by:
   a. Appending to `docs/adr/amendments.log` (always)
   b. Generating a new ADR file (for create/supersede operations)
4. Returns an AmendmentResult with details for audit trail

Decree patterns recognized:
- "create ADR-NNNN about <topic>"
- "amend ADR-XXXX to <change_description>"
- "supersede ADR-XXXX with ADR-YYYY"
- "deprecate ADR-XXXX"

This implements the decree-driven automation for ADR-0016 (Self-Rewriting
ADR Mechanism), closing its "target-for-v1.0" status as of v3.12.0.

Per ADR-0016 §3 — ADRs are immutable once Accepted. AdrAmender does NOT
modify the original ADR file. Instead, it:
- Appends to amendments.log (always — full audit trail)
- Generates new ADR files (only for create/supersede operations)
  The generated ADRs start as Proposed — human must mark Accepted.
"""
from __future__ import annotations

import os
import re
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


# Regex patterns for the 4 decree operations.
# ADR numbers are 4-digit zero-padded (0001-9999).
_CREATE_PATTERN = re.compile(
    r"\bcreate\s+ADR[-\s]?(\d{1,4})\s+about\s+(.+?)\s*$",
    re.IGNORECASE,
)
_AMEND_PATTERN = re.compile(
    r"\bamend\s+ADR[-\s]?(\d{1,4})\s+to\s+(.+?)\s*$",
    re.IGNORECASE,
)
_SUPERSEDE_PATTERN = re.compile(
    r"\bsupersede\s+ADR[-\s]?(\d{1,4})\s+with\s+ADR[-\s]?(\d{1,4})\s*$",
    re.IGNORECASE,
)
_DEPRECATE_PATTERN = re.compile(
    r"\bdeprecate\s+ADR[-\s]?(\d{1,4})\s*$",
    re.IGNORECASE,
)


class AdrAmenderError(RuntimeError):
    """Raised when AdrAmender cannot process a decree."""
    pass


@dataclass
class AmendmentResult:
    """Result of processing an amendment decree."""
    operation: str        # 'create' | 'amend' | 'supersede' | 'deprecate'
    target_adr: str       # formatted as 'ADR-XXXX' (4-digit zero-padded)
    new_adr: Optional[str] = None  # for 'supersede' operations
    topic_or_change: str = ""  # the topic (create) or change description (amend)
    decree_seq: int = 0   # the decree seq that triggered this amendment
    timestamp: str = ""
    log_entry: str = ""   # the line written to amendments.log
    new_adr_file: Optional[str] = None  # path to generated ADR file (if any)
    notes: List[str] = field(default_factory=list)


def _format_adr_id(num: int) -> str:
    """Format an ADR number as 'ADR-XXXX' (4-digit zero-padded)."""
    if not (1 <= num <= 9999):
        raise AdrAmenderError(f"ADR number out of range (1-9999): {num}")
    return f"ADR-{num:04d}"


def _parse_decree(decree_text: str) -> Tuple[str, Dict[str, Any]]:
    """Parse a decree text and return (operation, parsed_fields).

    Returns operation ∈ {'create', 'amend', 'supersede', 'deprecate'}.
    parsed_fields contains the captured groups.

    Raises AdrAmenderError if no pattern matches.
    """
    # Try each pattern.
    m = _CREATE_PATTERN.search(decree_text)
    if m:
        return "create", {
            "adr_num": int(m.group(1)),
            "topic": m.group(2).strip(),
        }

    m = _AMEND_PATTERN.search(decree_text)
    if m:
        return "amend", {
            "target_adr_num": int(m.group(1)),
            "change": m.group(2).strip(),
        }

    m = _SUPERSEDE_PATTERN.search(decree_text)
    if m:
        return "supersede", {
            "old_adr_num": int(m.group(1)),
            "new_adr_num": int(m.group(2)),
        }

    m = _DEPRECATE_PATTERN.search(decree_text)
    if m:
        return "deprecate", {
            "target_adr_num": int(m.group(1)),
        }

    raise AdrAmenderError(
        f"Decree text does not match any amendment pattern. "
        f"Recognized patterns: 'create ADR-XXXX about ...', "
        f"'amend ADR-XXXX to ...', 'supersede ADR-XXXX with ADR-YYYY', "
        f"'deprecate ADR-XXXX'. Got: {decree_text!r}"
    )


# Template for generated ADR files (per ADR-0026 §5).
_ADR_TEMPLATE = """# ADR-{adr_num} — {title}

**Date:** {date}
**Status:** Proposed (awaiting human review)
{supersedes_line}**Generated by:** AdrAmender from Decree #{decree_seq} (per ADR-0026)

## Context

{context}

## Decision

{decision}

## Consequences

- This ADR was auto-generated from Decree #{decree_seq}
- Human should review and amend before marking Accepted
- Once Accepted, this ADR becomes immutable per ADR-0016 §3
- The triggering decree remains in DecreeLog as the authority

## Verification

- `make verify` check 04 (ADRs follow template) — passes (template followed)
- `make verify` check 05 (AUDIT_RESPONSE cross-references all ADRs) — must
  be updated to add this ADR before final acceptance

## References

- ADR-0001 (Record Architecture Decisions) — bootstrap ADR pattern
- ADR-0016 (Self-Rewriting ADR Mechanism) — meta-process this ADR follows
- ADR-0021 (Decree as Supreme Law) — decree is the authority for this ADR
- ADR-0026 (Decree-Driven ADR Amendment Mechanism) — implemented by AdrAmender

## Self-reference

This ADR was generated by `AdrAmender.process()` from Decree #{decree_seq}.
The original decree text is in `~/.polymath-os/decrees.db`. To amend this
ADR, issue a new decree: `amend ADR-{adr_num} to <change>`.
"""


class AdrAmender:
    """Process decrees with category='amendment' per ADR-0026.

    Usage:
        amender = AdrAmender(adr_dir=Path('docs/adr'))
        # Decree #8: "amend ADR-0016 to require two-party review"
        result = amender.process(decree_seq=8, decree_text="amend ADR-0016 to require two-party review")
        # → AmendmentResult(operation='amend', target_adr='ADR-0016', ...)
        # → amendments.log gets a new line
    """

    def __init__(self, adr_dir: Optional[Path] = None, repo_root: Optional[Path] = None):
        """Initialize the AdrAmender.

        Args:
            adr_dir: path to docs/adr/ directory. If None, derived from repo_root.
            repo_root: path to repository root. If None, derived from this file's location.
        """
        if adr_dir is not None:
            self.adr_dir = Path(adr_dir)
        else:
            # Default: docs/adr/ relative to repo root.
            if repo_root is not None:
                self.adr_dir = Path(repo_root) / "docs" / "adr"
            else:
                # Find repo root by walking up from this file.
                here = Path(__file__).resolve()
                for parent in here.parents:
                    if (parent / "docs" / "adr").is_dir():
                        self.adr_dir = parent / "docs" / "adr"
                        break
                else:
                    # Fallback: relative to this file.
                    self.adr_dir = here.parents[2] / "docs" / "adr"

        self.amendments_log_path = self.adr_dir / "amendments.log"

    def process(self, decree_seq: int, decree_text: str, timestamp: Optional[str] = None) -> AmendmentResult:
        """Process an amendment decree.

        Args:
            decree_seq: the decree's sequence number in DecreeLog
            decree_text: the raw decree text
            timestamp: ISO 8601 UTC timestamp (default: now)

        Returns:
            AmendmentResult with operation details + log entry

        Raises:
            AdrAmenderError: if decree text doesn't match any pattern
        """
        if timestamp is None:
            timestamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

        operation, fields = _parse_decree(decree_text)

        if operation == "create":
            return self._create_adr(decree_seq, decree_text, timestamp, fields)
        elif operation == "amend":
            return self._amend_adr(decree_seq, decree_text, timestamp, fields)
        elif operation == "supersede":
            return self._supersede_adr(decree_seq, decree_text, timestamp, fields)
        elif operation == "deprecate":
            return self._deprecate_adr(decree_seq, decree_text, timestamp, fields)
        else:
            raise AdrAmenderError(f"Unknown operation: {operation}")

    def _create_adr(self, decree_seq: int, decree_text: str, timestamp: str, fields: Dict) -> AmendmentResult:
        adr_num = fields["adr_num"]
        topic = fields["topic"]
        target_adr = _format_adr_id(adr_num)
        title = topic[:80]  # truncate for title

        # Generate ADR file path.
        # Slugify the topic for the filename.
        slug = re.sub(r"[^a-z0-9]+", "-", topic.lower())[:60].strip("-")
        if not slug:
            slug = "untitled"
        adr_filename = f"{adr_num:04d}-{slug}.md"
        adr_filepath = self.adr_dir / adr_filename

        # Don't overwrite existing ADR.
        if adr_filepath.exists():
            return AmendmentResult(
                operation="create",
                target_adr=target_adr,
                topic_or_change=topic,
                decree_seq=decree_seq,
                timestamp=timestamp,
                log_entry=self._log_line(timestamp, decree_seq, "create", target_adr,
                                           f"FAILED: file already exists at {adr_filepath}"),
                notes=[f"ADR file {adr_filepath} already exists — no action taken"],
            )

        # Generate ADR content from template.
        content = _ADR_TEMPLATE.format(
            adr_num=f"{adr_num:04d}",
            title=title,
            date=timestamp,
            supersedes_line="",
            decree_seq=decree_seq,
            context=f"Decree #{decree_seq} (amendment) directed the creation of this ADR about: {topic}",
            decision=f"{decree_text}\n\nThe human issued this decree; it is the supreme authority for this ADR's existence (per ADR-0021).",
        )

        # Write the ADR file.
        try:
            self.adr_dir.mkdir(parents=True, exist_ok=True)
            with open(adr_filepath, "w", encoding="utf-8") as f:
                f.write(content)
        except OSError as e:
            raise AdrAmenderError(f"Cannot write ADR file {adr_filepath}: {e}")

        log_line = self._log_line(timestamp, decree_seq, "create", target_adr,
                                   f"created ADR file {adr_filename} about: {topic}")

        return AmendmentResult(
            operation="create",
            target_adr=target_adr,
            topic_or_change=topic,
            decree_seq=decree_seq,
            timestamp=timestamp,
            log_entry=log_line,
            new_adr_file=str(adr_filepath),
            notes=[f"Generated {adr_filepath}", "Status: Proposed (human must review and mark Accepted)"],
        )

    def _amend_adr(self, decree_seq: int, decree_text: str, timestamp: str, fields: Dict) -> AmendmentResult:
        target_num = fields["target_adr_num"]
        change = fields["change"]
        target_adr = _format_adr_id(target_num)

        log_line = self._log_line(timestamp, decree_seq, "amend", target_adr,
                                   f"amend to: {change}")

        return AmendmentResult(
            operation="amend",
            target_adr=target_adr,
            topic_or_change=change,
            decree_seq=decree_seq,
            timestamp=timestamp,
            log_entry=log_line,
            notes=[
                f"Amendment recorded in amendments.log",
                f"Original ADR-{target_num:04d} file is NOT modified (per ADR-0016 §3 immutability)",
                f"Human should review the change and consider issuing a superseding ADR",
            ],
        )

    def _supersede_adr(self, decree_seq: int, decree_text: str, timestamp: str, fields: Dict) -> AmendmentResult:
        old_num = fields["old_adr_num"]
        new_num = fields["new_adr_num"]
        old_adr = _format_adr_id(old_num)
        new_adr = _format_adr_id(new_num)

        # Try to generate the new ADR file (similar to create, but with Supersedes header).
        slug = f"supersedes-{old_num:04d}"
        adr_filename = f"{new_num:04d}-{slug}.md"
        adr_filepath = self.adr_dir / adr_filename

        if adr_filepath.exists():
            log_line = self._log_line(timestamp, decree_seq, "supersede", old_adr,
                                       f"supersede with {new_adr} — FAILED: file already exists")
            return AmendmentResult(
                operation="supersede",
                target_adr=old_adr,
                new_adr=new_adr,
                decree_seq=decree_seq,
                timestamp=timestamp,
                log_entry=log_line,
                notes=[f"ADR file {adr_filepath} already exists — no file generated"],
            )

        # Generate the new ADR file.
        content = _ADR_TEMPLATE.format(
            adr_num=f"{new_num:04d}",
            title=f"Supersedes {old_adr} (auto-generated)",
            date=timestamp,
            supersedes_line=f"**Supersedes:** {old_adr}\n",
            decree_seq=decree_seq,
            context=f"Decree #{decree_seq} (amendment) directed that {old_adr} be superseded by {new_adr}.",
            decision=f"{decree_text}\n\nThis ADR supersedes {old_adr}. The supersession is recorded in amendments.log. The original {old_adr} file remains immutable per ADR-0016 §3.",
        )

        try:
            self.adr_dir.mkdir(parents=True, exist_ok=True)
            with open(adr_filepath, "w", encoding="utf-8") as f:
                f.write(content)
        except OSError as e:
            raise AdrAmenderError(f"Cannot write ADR file {adr_filepath}: {e}")

        log_line = self._log_line(timestamp, decree_seq, "supersede", old_adr,
                                   f"superseded by {new_adr}; generated {adr_filename}")

        return AmendmentResult(
            operation="supersede",
            target_adr=old_adr,
            new_adr=new_adr,
            decree_seq=decree_seq,
            timestamp=timestamp,
            log_entry=log_line,
            new_adr_file=str(adr_filepath),
            notes=[
                f"Generated {adr_filepath} with Supersedes: {old_adr}",
                f"Original {old_adr} file NOT modified (per ADR-0016 §3)",
                f"Human must mark {new_adr} as Accepted before enforcement",
            ],
        )

    def _deprecate_adr(self, decree_seq: int, decree_text: str, timestamp: str, fields: Dict) -> AmendmentResult:
        target_num = fields["target_adr_num"]
        target_adr = _format_adr_id(target_num)

        log_line = self._log_line(timestamp, decree_seq, "deprecate", target_adr,
                                   f"deprecated by decree")

        return AmendmentResult(
            operation="deprecate",
            target_adr=target_adr,
            decree_seq=decree_seq,
            timestamp=timestamp,
            log_entry=log_line,
            notes=[
                f"Deprecation recorded in amendments.log",
                f"Original {target_adr} file NOT modified (per ADR-0016 §3 immutability)",
                f"Human should mark {target_adr} status as Deprecated in a follow-up commit",
            ],
        )

    def _log_line(self, timestamp: str, decree_seq: int, operation: str,
                  target_adr: str, description: str) -> str:
        """Format a line for amendments.log."""
        return f"[{timestamp}] Decree #{decree_seq} ({operation}): {target_adr} — {description}"

    def append_to_log(self, log_line: str) -> None:
        """Append a line to amendments.log (creates file if missing)."""
        self.adr_dir.mkdir(parents=True, exist_ok=True)
        with open(self.amendments_log_path, "a", encoding="utf-8") as f:
            f.write(log_line + "\n")

    def process_and_log(self, decree_seq: int, decree_text: str, timestamp: Optional[str] = None) -> AmendmentResult:
        """Process an amendment decree AND append the result to amendments.log.

        Convenience method — calls process() then append_to_log().
        """
        result = self.process(decree_seq, decree_text, timestamp)
        self.append_to_log(result.log_entry)
        return result

    def read_log(self) -> List[str]:
        """Read all entries from amendments.log. Returns empty list if file doesn't exist."""
        if not self.amendments_log_path.exists():
            return []
        with open(self.amendments_log_path, "r", encoding="utf-8") as f:
            return [line.rstrip("\n") for line in f if line.strip()]
